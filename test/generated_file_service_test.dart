import 'dart:io';
import 'dart:typed_data';

import 'package:aapkelawyer/services/generated_file_service.dart';
import 'package:aapkelawyer/services/legal_document_export_service.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:pdf/widgets.dart' as pw;

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();
  late Directory temporaryDirectory;

  setUp(() async {
    temporaryDirectory = await Directory.systemTemp.createTemp(
      'nyaysaarthi_file_test_',
    );
  });

  tearDown(() async {
    if (await temporaryDirectory.exists()) {
      await temporaryDirectory.delete(recursive: true);
    }
  });

  test('saves and validates a non-empty generated file', () async {
    final generated = await GeneratedFileService.saveBytes(
      bytes: Uint8List.fromList([1, 2, 3, 4]),
      fileName: 'Rent Agreement?.png',
      directory: temporaryDirectory,
    );

    expect(generated.name, 'Rent_Agreement.png');
    expect(generated.size, 4);
    expect(await File(generated.path).exists(), isTrue);
    expect(await File(generated.path).length(), greaterThan(0));
  });

  test('rejects empty generated bytes', () async {
    expect(
      () => GeneratedFileService.saveBytes(
        bytes: Uint8List(0),
        fileName: 'Empty.pdf',
        directory: temporaryDirectory,
      ),
      throwsA(isA<GeneratedFileException>()),
    );
  });

  test('the pdf package creates a simple PDF before file formatting', () async {
    final pdf = pw.Document();
    pdf.addPage(
      pw.Page(build: (context) => pw.Center(child: pw.Text('Test PDF'))),
    );

    final bytes = await pdf.save();

    expect(bytes, isNotEmpty);
    expect(String.fromCharCodes(bytes.take(4)), '%PDF');
  });

  test('creates a real, validated simple English PDF file', () async {
    final generated = await LegalDocumentExportService.createPdf(
      title: 'Rent Agreement 2026',
      content: '''
# RENT AGREEMENT

This agreement is made between [LANDLORD NAME] and [TENANT NAME].

## TERMS

1. The premises are located at [ADDRESS].
2. Monthly rent is [AMOUNT].

SIGNATURES:

Landlord: ____________________

Tenant: ____________________
''',
      directory: temporaryDirectory,
    );

    final file = File(generated.path);
    final bytes = await file.readAsBytes();
    expect(generated.name, 'Rent_Agreement_2026.pdf');
    expect(await file.exists(), isTrue);
    expect(bytes.length, greaterThan(100));
    expect(String.fromCharCodes(bytes.take(4)), '%PDF');
  });

  test(
    'creates a validated PDF containing Hindi, rupee, and punctuation',
    () async {
      final generated = await LegalDocumentExportService.createPdf(
        title: 'Unicode Legal Notice',
        content: '''
# कानूनी नोटिस

यह नोटिस ₹25,000 की बकाया राशि के संबंध में है।

“प्राप्तकर्ता” को भुगतान के लिए 15 दिन दिए जाते हैं — अन्यथा उचित कानूनी कार्रवाई की जा सकती है।

हस्ताक्षर: ____________________
''',
        directory: temporaryDirectory,
      );

      final file = File(generated.path);
      expect(await file.exists(), isTrue);
      expect(await file.length(), greaterThan(100));
      expect(String.fromCharCodes((await file.readAsBytes()).take(4)), '%PDF');
    },
  );

  test('creates a validated multi-page legal PDF', () async {
    final sections = List.generate(
      80,
      (index) =>
          '''
## Clause ${index + 1}

This clause records the parties' rights, duties, payment obligations, notice requirements, and remedies. It must be interpreted with the remaining agreement and applicable law.
''',
    ).join('\n');

    final generated = await LegalDocumentExportService.createPdf(
      title: 'Long Legal Agreement',
      content: '# LONG LEGAL AGREEMENT\n\n$sections\n\nSIGNATURES:',
      directory: temporaryDirectory,
    );

    final file = File(generated.path);
    expect(await file.exists(), isTrue);
    expect(await file.length(), greaterThan(5000));
    expect(String.fromCharCodes((await file.readAsBytes()).take(4)), '%PDF');
  });
}
